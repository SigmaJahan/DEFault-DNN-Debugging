#!/usr/bin/env python3
"""C: confusion matrix for fault diagnosis.

Trains a group-aware-CV RandomForest on faulty runs (trajectory features),
collects out-of-fold predictions, and writes a row-normalized confusion
matrix as a figure plus a per-class F1 table.

Outputs:
  output/analysis_artifacts/figures/diagnosis_confusion.pdf
  output/analysis_artifacts/tables/per_class_diagnosis.tex
  output/analysis_artifacts/diagnosis_confusion.json

Example:
  python3 analysis/diagnosis_confusion.py --data-root . \
      --out-dir output/analysis_artifacts
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import confusion_matrix, f1_score
from sklearn.pipeline import Pipeline
try:
    from sklearn.model_selection import StratifiedGroupKFold
except ImportError:
    StratifiedGroupKFold = None
from sklearn.model_selection import GroupKFold

from feature_builders import load_manifest, build_features


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", type=Path, required=True)
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--n-splits", type=int, default=5)
    ap.add_argument("--rf-estimators", type=int, default=200)
    ap.add_argument("--representation", default="trajectory",
                    choices=["snapshot", "trajectory"])
    ap.add_argument("--max-logs", type=int, default=None)
    args = ap.parse_args()

    df, repo_root = load_manifest(args.data_root)
    X, y_bin, y_cat, groups, _ = build_features(
        df, repo_root, representation=args.representation, max_logs=args.max_logs)

    mask = y_bin == 1
    Xb, yb, gb = X[mask], y_cat[mask], groups[mask]
    classes = sorted(np.unique(yb).tolist())

    pipe = Pipeline([
        ("imp", SimpleImputer(strategy="median")),
        ("clf", RandomForestClassifier(n_estimators=args.rf_estimators, random_state=7,
                                       n_jobs=-1, class_weight="balanced_subsample")),
    ])
    if StratifiedGroupKFold is not None:
        splitter = StratifiedGroupKFold(n_splits=args.n_splits, shuffle=True, random_state=7)
        it = splitter.split(Xb, yb, groups=gb)
    else:
        splitter = GroupKFold(n_splits=args.n_splits)
        it = splitter.split(Xb, yb, groups=gb)

    yt = np.empty(0, dtype=object)
    yp = np.empty(0, dtype=object)
    for tr, te in it:
        pipe.fit(Xb[tr], yb[tr])
        pred = pipe.predict(Xb[te])
        yt = np.concatenate([yt, yb[te]])
        yp = np.concatenate([yp, pred])

    cm = confusion_matrix(yt, yp, labels=classes)
    cm_norm = cm / cm.sum(axis=1, keepdims=True).clip(min=1)
    per_class_f1 = f1_score(yt, yp, labels=classes, average=None, zero_division=0)

    out_fig = args.out_dir / "figures"
    out_tab = args.out_dir / "tables"
    out_fig.mkdir(parents=True, exist_ok=True)
    out_tab.mkdir(parents=True, exist_ok=True)

    (args.out_dir / "diagnosis_confusion.json").write_text(json.dumps({
        "classes": classes,
        "confusion_counts": cm.tolist(),
        "confusion_row_normalized": cm_norm.tolist(),
        "per_class_f1": per_class_f1.tolist(),
    }, indent=2, default=float), encoding="utf-8")

    lines = ["% Auto-generated by analysis/diagnosis_confusion.py",
             "\\begin{tabular}{@{}lr@{}}\\toprule",
             "Fault Category & Per-class F1 \\\\ \\midrule"]
    for c, f in zip(classes, per_class_f1):
        lines.append(f"{c} & {f:.3f} \\\\")
    lines.append("\\bottomrule\\end{tabular}")
    (out_tab / "per_class_diagnosis.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    matplotlib.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Times New Roman", "Times", "Nimbus Roman", "DejaVu Serif"],
        "pdf.fonttype": 42, "ps.fonttype": 42,
        "savefig.dpi": 300, "savefig.bbox": "tight",
    })
    fig, ax = plt.subplots(figsize=(4.2, 3.6))
    im = ax.imshow(cm_norm, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(len(classes)))
    ax.set_yticks(range(len(classes)))
    ax.set_xticklabels(classes, rotation=45, ha="right", fontsize=7)
    ax.set_yticklabels(classes, fontsize=7)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    for i in range(len(classes)):
        for j in range(len(classes)):
            v = cm_norm[i, j]
            ax.text(j, i, f"{v:.2f}", ha="center", va="center",
                    fontsize=6, color="white" if v > 0.5 else "black")
    fig.colorbar(im, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(out_fig / "diagnosis_confusion.pdf")
    print(f"Wrote {out_fig / 'diagnosis_confusion.pdf'}")
    print(f"Wrote {out_tab / 'per_class_diagnosis.tex'}")
    print(f"Wrote {args.out_dir / 'diagnosis_confusion.json'}")


if __name__ == "__main__":
    main()
