#!/usr/bin/env python3
"""A+B: compare snapshot vs trajectory-summary feature representations.

Runs LogReg and RandForest on both representations for fault detection
and fault diagnosis, with the same group-aware CV and class-balanced
metrics as round 1. Always-faulty / Stratified dummies included as floors.

Outputs:
  output/analysis_artifacts/representation_results.json
  output/analysis_artifacts/tables/representation_results.tex
  output/analysis_artifacts/predictions_r2/*.npz   (for bootstrap reuse)

Example:
  python3 analysis/baseline_representations.py --data-root . \
      --out-dir output/analysis_artifacts
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    f1_score, balanced_accuracy_score, matthews_corrcoef,
    roc_auc_score, average_precision_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

try:
    from sklearn.model_selection import StratifiedGroupKFold
except ImportError:
    StratifiedGroupKFold = None
from sklearn.model_selection import GroupKFold

from feature_builders import load_manifest, build_features


def make_lr() -> Pipeline:
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("clf", LogisticRegression(solver="lbfgs", max_iter=2000,
                                   class_weight="balanced", random_state=7)),
    ])


def make_rf(n_estimators: int) -> Pipeline:
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("clf", RandomForestClassifier(n_estimators=n_estimators, random_state=7,
                                       n_jobs=-1, class_weight="balanced_subsample")),
    ])


def make_dummy(strategy: str, constant=None) -> Pipeline:
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("clf", DummyClassifier(strategy=strategy, constant=constant, random_state=7)),
    ])


def evaluate(model, X, y, groups, n_splits, is_multiclass) -> Dict[str, object]:
    if StratifiedGroupKFold is not None:
        splitter = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=7)
        it = splitter.split(X, y, groups=groups)
    else:
        splitter = GroupKFold(n_splits=n_splits)
        it = splitter.split(X, y, groups=groups)

    avg = "macro" if is_multiclass else "binary"
    yt = np.empty(0, dtype=y.dtype)
    yp = np.empty(0, dtype=y.dtype)
    ys: Optional[np.ndarray] = None

    for tr, te in it:
        model.fit(X[tr], y[tr])
        pred = model.predict(X[te])
        yt = np.concatenate([yt, y[te]])
        yp = np.concatenate([yp, pred])
        if not is_multiclass and hasattr(model, "predict_proba"):
            try:
                pr = model.predict_proba(X[te])[:, 1]
                ys = pr if ys is None else np.concatenate([ys, pr])
            except Exception:
                ys = None

    m: Dict[str, object] = {
        "f1": float(f1_score(yt, yp, average=avg, zero_division=0)),
        "macro_f1": float(f1_score(yt, yp, average="macro", zero_division=0)),
        "balanced_accuracy": float(balanced_accuracy_score(yt, yp)),
        "mcc": float(matthews_corrcoef(yt, yp)),
    }
    if not is_multiclass and ys is not None and len(np.unique(yt)) == 2:
        m["auprc"] = float(average_precision_score(yt, ys))
        m["auroc"] = float(roc_auc_score(yt, ys))
    else:
        m["auprc"] = float("nan")
        m["auroc"] = float("nan")
    m["_y_true"] = yt
    m["_y_pred"] = yp
    m["_y_score"] = ys
    return m


def write_table(results: List[Dict[str, object]], out_path: Path) -> None:
    lines = ["% Auto-generated by analysis/baseline_representations.py"]
    lines.append("\\begin{tabular}{@{}lllrrrr@{}}\\toprule")
    lines.append("Task & Features & Model & F1 & Macro-F1 & Bal.Acc & MCC \\\\ \\midrule")
    last = None
    for r in results:
        key = (r["task"], r["representation"])
        if last is not None and key != last:
            lines.append("\\midrule")
        last = key
        lines.append(
            f"{r['task']} & {r['representation']} & {r['model']} & "
            f"{r['f1']:.3f} & {r['macro_f1']:.3f} & "
            f"{r['balanced_accuracy']:.3f} & {r['mcc']:.3f} \\\\"
        )
    lines.append("\\bottomrule\\end{tabular}")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", type=Path, required=True)
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--n-splits", type=int, default=5)
    ap.add_argument("--rf-estimators", type=int, default=200)
    ap.add_argument("--max-logs", type=int, default=None)
    args = ap.parse_args()

    df, repo_root = load_manifest(args.data_root)
    tables = args.out_dir / "tables"
    preds = args.out_dir / "predictions_r2"
    tables.mkdir(parents=True, exist_ok=True)
    preds.mkdir(parents=True, exist_ok=True)

    results: List[Dict[str, object]] = []

    for rep in ["snapshot", "trajectory"]:
        print(f"=== representation: {rep} ===", flush=True)
        X, y_bin, y_cat, groups, feat_names = build_features(
            df, repo_root, representation=rep, max_logs=args.max_logs)
        print(f"  X shape: {X.shape}", flush=True)

        det_models = [
            ("Always-faulty", make_dummy("constant", constant=1)),
            ("Stratified", make_dummy("stratified")),
            ("LogReg", make_lr()),
            ("RandForest", make_rf(args.rf_estimators)),
        ]
        for name, pipe in det_models:
            res = evaluate(pipe, X, y_bin, groups, args.n_splits, is_multiclass=False)
            results.append({"task": "Detection", "representation": rep, "model": name, **res})
            print(f"  Detection/{name}: F1={res['f1']:.3f} MCC={res['mcc']:.3f}", flush=True)

        mask = y_bin == 1
        Xb, yb, gb = X[mask], y_cat[mask], groups[mask]
        diag_models = [
            ("Stratified", make_dummy("stratified")),
            ("LogReg", make_lr()),
            ("RandForest", make_rf(args.rf_estimators)),
        ]
        for name, pipe in diag_models:
            res = evaluate(pipe, Xb, yb, gb, args.n_splits, is_multiclass=True)
            results.append({"task": "Diagnosis", "representation": rep, "model": name, **res})
            print(f"  Diagnosis/{name}: MacroF1={res['macro_f1']:.3f} MCC={res['mcc']:.3f}", flush=True)

    for r in results:
        tag = f"{r['task']}__{r['representation']}__{r['model']}".replace(" ", "_")
        sc = r["_y_score"]
        np.savez_compressed(
            preds / f"{tag}.npz",
            y_true=r["_y_true"], y_pred=r["_y_pred"],
            y_score=sc if sc is not None else np.array([]),
        )

    clean = [{k: v for k, v in r.items() if not k.startswith("_")} for r in results]
    (args.out_dir / "representation_results.json").write_text(
        json.dumps(clean, indent=2, default=float), encoding="utf-8")
    write_table(clean, tables / "representation_results.tex")
    print(f"Wrote {args.out_dir / 'representation_results.json'}")
    print(f"Wrote {tables / 'representation_results.tex'}")
    print(f"Wrote per-fold predictions under {preds}")


if __name__ == "__main__":
    main()
