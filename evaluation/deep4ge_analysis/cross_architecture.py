#!/usr/bin/env python3
"""E: cross-architecture generalization for fault detection.

For each held-out architecture family (FNN, CNN, RNN): train a detector on
the other two families, test on the held-out one. Reports F1, balanced
accuracy, and MCC per held-out family, plus the in-distribution score
(group-aware CV within the union of all families) as a reference.

Outputs:
  output/analysis_artifacts/cross_architecture.json
  output/analysis_artifacts/tables/cross_architecture.tex

Example:
  python3 analysis/cross_architecture.py --data-root . \
      --out-dir output/analysis_artifacts
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

import numpy as np

from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import f1_score, balanced_accuracy_score, matthews_corrcoef
from sklearn.pipeline import Pipeline
try:
    from sklearn.model_selection import StratifiedGroupKFold
except ImportError:
    StratifiedGroupKFold = None
from sklearn.model_selection import GroupKFold

from feature_builders import load_manifest, build_features, load_architecture_map


def make_rf(n_estimators: int) -> Pipeline:
    return Pipeline([
        ("imp", SimpleImputer(strategy="median")),
        ("clf", RandomForestClassifier(n_estimators=n_estimators, random_state=7,
                                       n_jobs=-1, class_weight="balanced_subsample")),
    ])


def score(y_true, y_pred) -> dict:
    return {
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
        "mcc": float(matthews_corrcoef(y_true, y_pred)),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", type=Path, required=True)
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--n-splits", type=int, default=5)
    ap.add_argument("--rf-estimators", type=int, default=200)
    ap.add_argument("--representation", default="trajectory",
                    choices=["snapshot", "trajectory"])
    ap.add_argument("--max-logs", type=int, default=None)
    args = ap.parse_args()

    df, repo_root = load_manifest(args.data_root)
    arch_map = load_architecture_map(args.data_root)

    X, y_bin, y_cat, groups, _ = build_features(
        df, repo_root, representation=args.representation, max_logs=args.max_logs)
    arch = np.array([arch_map.get(g, "UNKNOWN") for g in groups])

    families = ["FNN", "CNN", "RNN"]
    rows = []

    for held in families:
        train_mask = (arch != held) & (arch != "UNKNOWN")
        test_mask = arch == held
        if test_mask.sum() == 0 or train_mask.sum() == 0:
            continue
        pipe = make_rf(args.rf_estimators)
        pipe.fit(X[train_mask], y_bin[train_mask])
        pred = pipe.predict(X[test_mask])
        s = score(y_bin[test_mask], pred)
        rows.append({"setting": f"train!={held}, test={held}", "held_out": held,
                     "n_test": int(test_mask.sum()), **s})
        print(f"held-out {held}: F1={s['f1']:.3f} BalAcc={s['balanced_accuracy']:.3f} MCC={s['mcc']:.3f}")

    if StratifiedGroupKFold is not None:
        splitter = StratifiedGroupKFold(n_splits=args.n_splits, shuffle=True, random_state=7)
        it = splitter.split(X, y_bin, groups=groups)
    else:
        splitter = GroupKFold(n_splits=args.n_splits)
        it = splitter.split(X, y_bin, groups=groups)
    yt = np.empty(0, dtype=int)
    yp = np.empty(0, dtype=int)
    for tr, te in it:
        pipe = make_rf(args.rf_estimators)
        pipe.fit(X[tr], y_bin[tr])
        yt = np.concatenate([yt, y_bin[te]])
        yp = np.concatenate([yp, pipe.predict(X[te])])
    s = score(yt, yp)
    rows.append({"setting": "in-distribution (group CV, all families)",
                 "held_out": "none", "n_test": int(len(yt)), **s})
    print(f"in-distribution: F1={s['f1']:.3f} BalAcc={s['balanced_accuracy']:.3f} MCC={s['mcc']:.3f}")

    (args.out_dir / "cross_architecture.json").write_text(
        json.dumps(rows, indent=2, default=float), encoding="utf-8")

    tab = args.out_dir / "tables"
    tab.mkdir(parents=True, exist_ok=True)
    lines = ["% Auto-generated by analysis/cross_architecture.py",
             "\\begin{tabular}{@{}lrrr@{}}\\toprule",
             "Setting & F1 & Bal.Acc & MCC \\\\ \\midrule"]
    for r in rows:
        label = r["held_out"] if r["held_out"] != "none" else "in-distribution"
        lines.append(f"{label} & {r['f1']:.3f} & {r['balanced_accuracy']:.3f} & {r['mcc']:.3f} \\\\")
    lines.append("\\bottomrule\\end{tabular}")
    (tab / "cross_architecture.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out_dir / 'cross_architecture.json'}")
    print(f"Wrote {tab / 'cross_architecture.tex'}")


if __name__ == "__main__":
    main()
